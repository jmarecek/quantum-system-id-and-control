"""ch04_observability.py -- observability of open quantum systems, numerically.

Builds the coherence-vector (Bloch) representation  x' = A x + beta  of a GKSL
master equation directly from the superoperator, forms the Kalman observability
matrix for a choice of measured observables, computes the dimension of the
observable subspace, and the Lie closure of a set of control Hamiltonians.

Writes  figures/ch04_observability.tex  (observable-subspace dimension of the
two-qubit example of Parvaiz et al. versus Krylov order, for several readouts)
and     figures/ch04_singular.tex       (singular values of the observability
matrix of a damped qubit for different readouts).
"""
import itertools
import os
import sys

import numpy as np

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import tikzexport as T

I2, X, Y, Z = T.pauli()


def pauli_basis(q):
    """Orthonormal traceless Hermitian basis F_1..F_{4^q-1} (Pauli strings / sqrt(2^q))."""
    strings = itertools.product([I2, X, Y, Z], repeat=q)
    mats = []
    for s in strings:
        M = s[0]
        for m in s[1:]:
            M = np.kron(M, m)
        mats.append(M)
    mats = mats[1:]                                 # drop the identity
    return [M / np.sqrt(2 ** q) for M in mats]


def lindbladian(H, jumps):
    """Return the map rho -> -i[H,rho] + sum_k (L rho L^+ - 1/2 {L^+ L, rho})."""
    def L(rho):
        out = -1j * (H @ rho - rho @ H)
        for J in jumps:
            JJ = J.conj().T @ J
            out += J @ rho @ J.conj().T - 0.5 * (JJ @ rho + rho @ JJ)
        return out
    return L


def coherence_representation(L, basis):
    """Matrix A and vector beta with  x' = A x + beta,  x_j = Tr(F_j rho)."""
    n = len(basis)
    d = basis[0].shape[0]
    A = np.zeros((n, n))
    beta = np.zeros(n)
    for k, Fk in enumerate(basis):
        LFk = L(Fk)
        for j, Fj in enumerate(basis):
            A[j, k] = np.real(np.trace(Fj @ LFk))
    Lid = L(np.eye(d) / d)
    for j, Fj in enumerate(basis):
        beta[j] = np.real(np.trace(Fj @ Lid))
    return A, beta


def observability_matrix(A, C):
    """Kalman observability matrix  [C; CA; ...; CA^{n-1}]."""
    n = A.shape[0]
    blocks, M = [], C.copy()
    for _ in range(n):
        blocks.append(M)
        M = M @ A
    return np.vstack(blocks)


def lie_closure(generators, tol=1e-9):
    """Dimension of the real Lie algebra generated by anti-Hermitian matrices."""
    def vec(M):
        return np.concatenate([M.real.ravel(), M.imag.ravel()])
    basis = []
    for G in generators:
        v = vec(G)
        if np.linalg.matrix_rank(np.array(basis + [v]), tol) > len(basis):
            basis.append(v)
    elems = list(generators)
    k = 0
    while k < len(elems):
        for G in list(elems):
            Cm = elems[k] @ G - G @ elems[k]
            v = vec(Cm)
            if np.linalg.norm(v) > tol and \
               np.linalg.matrix_rank(np.array(basis + [v]), tol) > len(basis):
                basis.append(v)
                elems.append(Cm)
        k += 1
    return len(basis)


def readout_matrix(observables, basis):
    """Rows = expansion coefficients of the measured observables in the basis."""
    return np.array([[np.real(np.trace(F @ O)) for F in basis] for O in observables])


def observable_dimension(A, C, kmax):
    """dim span{C, CA, ..., CA^k} for k = 0..kmax."""
    dims, M, rows = [], C.copy(), []
    for _ in range(kmax + 1):
        rows.append(M)
        dims.append(np.linalg.matrix_rank(np.vstack(rows), 1e-9))
        M = M @ A
    return dims


