    # sigma_- = |0><1| lowers to the ground state |0>; H = -(omega/2) sigma_z (as in Chapter 3)
    sm, sp = (X + 1j * Y) / 2, (X - 1j * Y) / 2
    assert np.allclose(sm, [[0, 1], [0, 0]])
    k1 = lambda P: np.kron(P, I2)
    k2 = lambda P: np.kron(I2, P)

    # --- two-qubit example (Zhang & Sarovar; Parvaiz et al.) -----------------
    w1, w2, delta = 1.0, 1.3, 0.4
    gz, gm, gp = 0.05, 0.08, 0.02
    H = -w1 / 2 * k1(Z) - w2 / 2 * k2(Z) + delta * (k1(sp) @ k2(sm) + k1(sm) @ k2(sp))
    jumps = []
    for kk in (k1, k2):
        jumps += [np.sqrt(gz / 2) * kk(Z), np.sqrt(2 * gm) * kk(sm), np.sqrt(2 * gp) * kk(sp)]
    basis4 = pauli_basis(2)
    A, beta = coherence_representation(lindbladian(H, jumps), basis4)
    Aemb = np.zeros((16, 16)); Aemb[:15, :15] = A; Aemb[:15, 15] = beta     # affine embedding [x; 1]
