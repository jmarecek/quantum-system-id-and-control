"""ch13_qcpop_vs_grape.py -- global optimum by enumeration vs local gradient search.

Toy version of the QCPOP-vs-GRAPE comparison: a three-level system with the drift and
control Hamiltonians of the globally-optimal-control paper, a 3-segment piecewise-constant
control on [0, T] and a target unitary generated by a hidden control.  The global optimum is
found by enumerating a grid of controls (the role played by polynomial optimisation), local
gradient descent is run from random initial guesses (the role played by GRAPE), and the
histogram of the final infidelities is compared with the global value.
Writes figures/ch13_qcpop_vs_grape.tex.
"""
import sys, os
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import numpy as np
from scipy.linalg import expm
from scipy.optimize import minimize
import tikzexport as T

H0 = np.diag([0.0, 0.515916, 1.0])
V = np.array([[0, 0.707107, 0], [0.707107, 0, 1], [0, 1, 0]])
Ttot, m = 0.5, 3                                               # horizon and number of segments
dt = Ttot / m


def propagator(E):
    U = np.eye(3, dtype=complex)
    for Ej in E:
        U = expm(-1j * dt * (H0 + Ej * V)) @ U
    return U


def infidelity(E, Ustar):
    return 1 - abs(np.trace(propagator(E).conj().T @ Ustar)) / 3


def main():
    rng = np.random.RandomState(3)
    E_hidden = rng.uniform(-8, 8, size=m)
    Ustar = propagator(E_hidden)
    # "polynomial optimisation": exhaustive enumeration on a grid, then a polish
    grid = np.linspace(-10, 10, 33)
    best, bestE = np.inf, None
    for a in grid:
        for b in grid:
            for c in grid:
                f = infidelity([a, b, c], Ustar)
                if f < best:
                    best, bestE = f, np.array([a, b, c])
    res = minimize(lambda E: infidelity(E, Ustar), bestE, method="BFGS")
    glob = res.fun
    # "GRAPE": local gradient descent from random starts
    finals = []
    for k in range(200):
        E0 = rng.uniform(-10, 10, size=m)
        r = minimize(lambda E: infidelity(E, Ustar), E0, method="BFGS")
        finals.append(max(r.fun, 1e-12))
    finals = np.array(finals)
    print("global infidelity %.2e; local search: median %.2e, fraction within 1e-3 of global: %.2f"
          % (glob, np.median(finals), np.mean(finals < glob + 1e-3)))
    edges = np.linspace(-12, 0, 25)                            # histogram of log10(infidelity)
    counts, _ = np.histogram(np.log10(finals), bins=edges)
    centres = 0.5 * (edges[1:] + edges[:-1])
    body = ["\\begin{axis}[ybar interval, width=0.85\\linewidth, height=0.5\\linewidth,",
            "  xlabel={$\\log_{10}$ infidelity of local search}, ylabel={number of runs (of 200)},",
            "  ymin=0, tick label style={font=\\footnotesize}, legend style={font=\\footnotesize}, legend pos=north west]",
            "\\addplot[fill=qocA!60, draw=qocA] coordinates {%s};" % " ".join("(%.3f,%d)" % (e, c) for e, c in zip(edges[:-1], list(counts))) ,
            "\\addlegendentry{gradient descent, random starts}",
            "\\draw[qocB, very thick, dashed] (axis cs:%.3f,0) -- (axis cs:%.3f,%d) node[pos=0.9, right, font=\\footnotesize] {global optimum};" % (np.log10(max(glob, 1e-12)), np.log10(max(glob, 1e-12)), max(counts)),
            "\\end{axis}"]
    # ybar interval needs one more coordinate than bars
    body[3] = body[3].replace("};", " (%.3f,%d)};" % (edges[-1], counts[-1]))
    T.write_tikz("ch13_qcpop_vs_grape", "\n".join(body))


if __name__ == "__main__":
    main()
